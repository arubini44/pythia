/// Case-insensitive keyword check.
pub fn is_keyword(word: &str) -> bool {
    // Longest keyword is 22 bytes; avoid allocating for longer words.
    if word.len() > 24 || !word.is_ascii() {
        return false;
    }
    let mut buf = [0u8; 24];
    let upper = &mut buf[..word.len()];
    upper.copy_from_slice(word.as_bytes());
    upper.make_ascii_uppercase();
    let upper = std::str::from_utf8(upper).expect("ascii");
    KEYWORDS.binary_search(&upper).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sorted() {
        assert!(
            KEYWORDS.windows(2).all(|w| w[0] < w[1]),
            "KEYWORDS must be sorted"
        );
    }

    #[test]
    fn lookup() {
        assert!(is_keyword("select"));
        assert!(is_keyword("Pls_Integer"));
        assert!(!is_keyword("employees"));
    }
}
